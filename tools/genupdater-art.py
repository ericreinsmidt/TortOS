#!/usr/bin/env python3
"""tools/tortos-update/art.h, the updater's pictures, from TortOS's own drawing.

The updater writes a release after TortOS has stopped, with no font library,
so what it shows is drawn ahead of time by TortOS's panel code and carried in
the updater: the Writing, Checking and stopped-while-writing screens without
the parts that change, the glyphs for those parts, and where they go. Each
is xz-compressed, as the updater already has XZ Embedded for the image.

Run from the TortOS checkout, with a host build (make native) pointed at an
empty card, so the background is the plain one:

    mkdir -p /tmp/card/Roms /tmp/art
    TORTOS_ROOT=<a root with res/ and systems.cfg> TORTOS_CARD=/tmp/card \\
    TORTOS_ROMS=/tmp/card/Roms TORTOS_USERDATA=/tmp/card/u TORTOS_SHARED=/tmp/card/s \\
    TORTOS_FONT=res/fonts/menu.ttf build-native/tortos --updater-art /tmp/art
    python3 tools/genupdater-art.py /tmp/art > tools/tortos-update/art.h

Run again whenever the menus' look or the updater's wording changes.
"""
import lzma
import os
import sys

art = sys.argv[1]


def xz(data):
    # CRC32, the check XZ Embedded always has; LZMA2, the only filter it needs
    return lzma.compress(data, format=lzma.FORMAT_XZ, check=lzma.CHECK_CRC32,
                         preset=9 | lzma.PRESET_EXTREME)


def array(name, data):
    lines = [f"static const unsigned char {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


layout = {}
for line in open(os.path.join(art, "layout.txt")):
    key, *nums = line.split()
    layout[key] = [int(n) for n in nums]
w, h = layout["screen"]

pieces = []
for line in open(os.path.join(art, "pieces.txt")):
    key, pw, ph, off = line.split()
    pieces.append((key, int(pw), int(ph), int(off)))
names = {"head-prefix": "ART_HEAD_PREFIX", "head-.": "ART_HEAD_DOT",
         "value-%": "ART_VALUE_PERCENT", "bar-fill": "ART_BAR_FILL"}
for d in "0123456789":
    names[f"head-{d}"] = f"ART_HEAD_{d}"
    names[f"value-{d}"] = f"ART_VALUE_{d}"

screens = ["writing", "checking", "failed"]
raw = {s: open(os.path.join(art, f"{s}.rgba"), "rb").read() for s in screens}
for s in screens:
    assert len(raw[s]) == w * h * 4, s
bin_ = open(os.path.join(art, "pieces.bin"), "rb").read()

out = [
    "/* SPDX-License-Identifier: GPL-3.0-or-later */",
    "/* GENERATED by tools/genupdater-art.py from TortOS's own drawing",
    " * (--updater-art): don't edit, run it again (its comment says how). The",
    " * updater's three screens without the parts that change, the glyphs for",
    " * those parts, and where they go, all on a {}x{} screen. Text drawn in".format(w, h),
    " * Josefin Sans (SIL Open Font License 1.1), as TortOS's menus are. */",
    "#ifndef TORTOS_UPDATE_ART_H",
    "#define TORTOS_UPDATE_ART_H",
    "",
    "#include <stdint.h>",
    "",
    f"#define ART_W {w}",
    f"#define ART_H {h}",
    "/* The heading, centered on HEAD_X; the value, right-aligned to VALUE_X;",
    " * each glyph's top-left at the y given. The bar's track is in the screens. */",
    f"#define ART_HEAD_X {layout['head'][0]}",
    f"#define ART_HEAD_Y {layout['head'][1]}",
    f"#define ART_VALUE_X {layout['value'][0]}",
    f"#define ART_VALUE_Y {layout['value'][1]}",
    f"#define ART_BAR_X {layout['bar'][0]}",
    f"#define ART_BAR_Y {layout['bar'][1]}",
    f"#define ART_BAR_W {layout['bar'][2]}",
    f"#define ART_BAR_H {layout['bar'][3]}",
    "",
    "/* Pieces: RGBA, the color already multiplied by the coverage in A */",
    "enum {",
]
for key, *_ in pieces:
    out.append(f"\t{names[key]},")
out += ["\tART_PIECES", "};", "",
        "typedef struct { uint16_t w, h; uint32_t offset; } art_piece;", "",
        "static const art_piece art_pieces[ART_PIECES] = {"]
for key, pw, ph, off in pieces:
    out.append(f"\t[{names[key]}] = {{ {pw}, {ph}, {off} }},")
out += ["};", "", f"#define ART_PIECES_BYTES {len(bin_)}", ""]
for s in screens:
    out.append(array(f"art_{s}_xz", xz(raw[s])))
    out.append("")
out.append(array("art_pieces_xz", xz(bin_)))
out += ["", "#endif", ""]
sys.stdout.write("\n".join(out))
