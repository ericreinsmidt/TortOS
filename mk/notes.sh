#!/bin/sh
# The texts the systems row's card shows (src/main.c), as base64, into a
# generated header: from local/notes.txt, one per line, when the checkout has
# one with any text in it, and otherwise the line below. mk/cross.mk and
# mk/native.mk run it.
#
#   mk/notes.sh build/notes.h
#
# The header is replaced only when it changes, so an unchanged list doesn't
# force a relink.
set -e
OUT=$1
NOTES=$(dirname "$0")/../local/notes.txt

line() { printf '\t"%s",\n' "$(printf '%s' "$1" | base64 | tr -d '\n')"; }

mkdir -p "$(dirname "$OUT")"
LINES=
if [ -f "$NOTES" ]; then
	LINES=$(tr -d '\r' < "$NOTES" | while IFS= read -r text || [ -n "$text" ]; do
		if [ -n "$(printf '%s' "$text" | tr -d ' \t')" ]; then line "$text"; fi
	done)
fi
if [ -n "$LINES" ]; then
	echo "notes: $(printf '%s\n' "$LINES" | wc -l | tr -d ' ') from local/notes.txt" >&2
else
	LINES=$(line "You found it.")
	echo "notes: the default" >&2
fi
{
	echo '/* Generated by mk/notes.sh. */'
	echo 'static const char *const SEQ_TEXT[] = {'
	printf '%s\n' "$LINES"
	echo '};'
} > "$OUT.new"
cmp -s "$OUT.new" "$OUT" 2>/dev/null || mv -f "$OUT.new" "$OUT"
rm -f "$OUT.new"
